/** Generate only the consequence contracts and their referenced schemas. */
import { readFile, writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";

const document = JSON.parse(await readFile(new URL("../../docs/openapi/v1.json", import.meta.url), "utf8"));
const schemas = {};
const pending = ["GraphConsequenceRequest", "GraphConsequenceResponse"];
while (pending.length) {
  const name = pending.pop();
  if (name in schemas) continue;
  const schema = document.components.schemas[name];
  if (!schema) throw new Error(`Missing schema: ${name}`);
  schemas[name] = schema;
  for (const match of JSON.stringify(schema).matchAll(/#\/components\/schemas\/([^"\\]+)/g)) pending.push(match[1]);
}
const ast = await openapiTS({ openapi: "3.1.0", info: document.info, paths: {}, components: { schemas } });
const output = "// Generated by ui/scripts/codegen-consequence-sdk.mjs; do not edit.\n" + astToString(ast);
const path = new URL("../../sdks/typescript-client/src/graph-consequence.generated.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if (await readFile(path, "utf8") !== output) throw new Error("Consequence SDK schema drift; run the owning generator.");
} else await writeFile(path, output);
