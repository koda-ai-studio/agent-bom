"""Generate the decorative globe from Natural Earth 5.1.2 land (public domain).

Run: python3 ui/scripts/generate-internet-globe.py /path/to/ne_110m_land.geojson
Source: https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_land.geojson
License: https://www.naturalearthdata.com/about/terms-of-use/
No network access, runtime geographic dependency, or political boundaries.
"""

import hashlib
import json
import math
import sys
from pathlib import Path

SOURCE_SHA = "9e0729ee253ca7d7a5c4ae9395fb1902264c5377c52e224d13dd85010e2835d9"


def project(point):
    """Atlantic-centered orthographic globe; back-facing coasts follow the limb."""
    longitude, latitude = map(math.radians, point)
    longitude += math.radians(25)
    tilt = math.radians(15)
    x = math.cos(latitude) * math.sin(longitude)
    y = math.cos(tilt) * math.sin(latitude) - math.sin(tilt) * math.cos(latitude) * math.cos(longitude)
    depth = math.sin(tilt) * math.sin(latitude) + math.cos(tilt) * math.cos(latitude) * math.cos(longitude)
    if depth < 0:
        radius = math.hypot(x, y)
        x, y = x / radius, y / radius
    return (50 + 47 * x, 50 - 47 * y, depth)


def simplify(points, tolerance=0.25):
    """Keep coast detail visible at glyph size, discard subpixel noise."""
    if len(points) < 3:
        return points
    ax, ay = points[0][:2]
    bx, by = points[-1][:2]
    dx, dy = bx - ax, by - ay
    length = dx * dx + dy * dy
    distances = []
    for px, py, *_ in points[1:-1]:
        t = max(0, min(1, ((px - ax) * dx + (py - ay) * dy) / length)) if length else 0
        distances.append(math.hypot(px - ax - t * dx, py - ay - t * dy))
    farthest = max(distances, default=0)
    if farthest <= tolerance:
        return [points[0], points[-1]]
    index = distances.index(farthest) + 1
    return simplify(points[: index + 1], tolerance)[:-1] + simplify(points[index:], tolerance)


def main():
    source = Path(sys.argv[1]).read_bytes()
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA:
        raise SystemExit("Unexpected Natural Earth source digest")
    paths = []
    for feature in json.loads(source)["features"]:
        geometry = feature["geometry"]
        polygons = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
        for polygon in polygons:
            points = [project(point) for point in polygon[0]]
            if not any(point[2] > 0 for point in points):
                continue
            points = simplify(points)
            area = abs(sum(a[0] * b[1] - b[0] * a[1] for a, b in zip(points, points[1:]))) / 2
            if area < 1:
                continue
            paths.append("M" + "L".join(f"{x:.2f},{y:.2f}" for x, y, _ in points) + "Z")
    target = Path(__file__).resolve().parents[1] / "lib/internet-land.generated.ts"
    target.write_text(
        "// Generated by ui/scripts/generate-internet-globe.py; Natural Earth 5.1.2, public domain.\n"
        + f"// Source SHA-256: {SOURCE_SHA}\n"
        + "export const INTERNET_LAND = "
        + json.dumps(paths, indent=2)
        + ";\n"
    )


if __name__ == "__main__":
    main()
