#!/usr/bin/env python3
"""Load, verify and render the banner integration manifest.

``docs/images/integrations-manifest.json`` is the one list of integrations the
README banner and the generated integration tables name. Every entry points at
the code that implements it; :func:`unresolved_refs` and :func:`uncovered_sources`
keep the list honest in both directions.
"""

from __future__ import annotations

import ast
import importlib.util
import json
import sys
import typing
from dataclasses import dataclass
from functools import cache
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "docs" / "images" / "integrations-manifest.json"
BLOCK_BEGIN = "<!-- integrations:begin (generated by scripts/render_social_preview_svg.py; do not edit) -->"
BLOCK_END = "<!-- integrations:end -->"
DOC_SURFACES = (
    ROOT / "README.md",
    ROOT / "docs" / "registry" / "PYPI_README.md",
    ROOT / "docs" / "registry" / "DOCKER_HUB_README.md",
    ROOT / "site-docs" / "index.md",
)


@dataclass(frozen=True)
class Integration:
    name: str
    implements: tuple[str, ...]
    logo: str | None = None


@dataclass(frozen=True)
class Group:
    id: str
    title: str
    integrations: tuple[Integration, ...]

    @property
    def logos(self) -> tuple[Integration, ...]:
        return tuple(item for item in self.integrations if item.logo)

    @property
    def text_only(self) -> tuple[Integration, ...]:
        return tuple(item for item in self.integrations if not item.logo)


@dataclass(frozen=True)
class Manifest:
    groups: tuple[Group, ...]
    evidence_out: Group
    hidden: dict[str, str]
    trademark_note: str

    def integrations(self) -> list[Integration]:
        return [item for group in (*self.groups, self.evidence_out) for item in group.integrations]


def _group(raw: dict, default_id: str = "") -> Group:
    items = tuple(
        Integration(name=item["name"], implements=tuple(item["implements"]), logo=item.get("logo")) for item in raw["integrations"]
    )
    return Group(id=raw.get("id", default_id), title=raw["title"], integrations=items)


def load(path: Path = MANIFEST) -> Manifest:
    raw = json.loads(path.read_text(encoding="utf-8"))
    return Manifest(
        groups=tuple(_group(group) for group in raw["groups"]),
        evidence_out=_group(raw["evidence_out"], "evidence_out"),
        hidden=dict(raw["hidden"]),
        trademark_note=raw["trademark_note"],
    )


def _module_file(module: str) -> Path | None:
    spec = importlib.util.find_spec(module)
    return Path(spec.origin) if spec and spec.origin else None


@cache
def _top_level_names(module: str) -> frozenset[str]:
    path = _module_file(module)
    if path is None:
        return frozenset()
    names: set[str] = set()
    for node in ast.parse(path.read_text(encoding="utf-8")).body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            names.add(node.name)
        elif isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            names.update(target.id for target in targets if isinstance(target, ast.Name))
    return frozenset(names)


# Clients read from a catalog instead of a per-platform config path.
_ALTERNATE_CLIENT_DISCOVERY = {"docker-mcp": "agent_bom.discovery.local_sources:discover_docker_mcp"}


@cache
def registered_sources() -> dict[str, frozenset[str]]:
    """Every discoverable source the code registers, keyed by reference kind."""
    from agent_bom.cloud import _BUILTIN_PROVIDERS
    from agent_bom.cloud.vector_db import VECTOR_DB_PORTS
    from agent_bom.connectors import _BUILTIN_CONNECTORS
    from agent_bom.connectors.endpoints.models import ConnectionCreate
    from agent_bom.discovery.platform_config import CONFIG_LOCATIONS
    from agent_bom.domain.inventory_types import AgentType
    from agent_bom.export.destinations import SUPPORTED_EXPORT_KINDS
    from agent_bom.trace_connectors import LANGFUSE, LANGSMITH

    endpoint_annotation = ConnectionCreate.model_fields["provider"].annotation
    return {
        "cloud_provider": frozenset(_BUILTIN_PROVIDERS),
        "agent_type": frozenset(agent.value for agent in AgentType),
        "agent_type_discovered": frozenset(agent.value for agent, paths in CONFIG_LOCATIONS.items() if any(paths.values()))
        | frozenset(name for name, symbol in _ALTERNATE_CLIENT_DISCOVERY.items() if ref_resolves(f"symbol:{symbol}")),
        "connector": frozenset(_BUILTIN_CONNECTORS),
        "trace_connector": frozenset({LANGFUSE, LANGSMITH}),
        "export_kind": frozenset(SUPPORTED_EXPORT_KINDS),
        "vector_db": frozenset(VECTOR_DB_PORTS),
        "endpoint_provider": frozenset(typing.get_args(endpoint_annotation)),
    }


def ref_resolves(ref: str) -> bool:
    kind, _, value = ref.partition(":")
    if kind == "symbol":
        module, _, attr = value.rpartition(":")
        return bool(module) and attr in _top_level_names(module)
    sources = registered_sources()
    if kind == "agent_type":
        return value in sources["agent_type_discovered"]
    return value in sources.get(kind, frozenset())


def unresolved_refs(manifest: Manifest) -> list[str]:
    refs = [ref for item in manifest.integrations() for ref in item.implements]
    return [ref for ref in refs if not ref_resolves(ref)]


def uncovered_sources(manifest: Manifest) -> list[str]:
    listed = {ref for item in manifest.integrations() for ref in item.implements} | set(manifest.hidden)
    required = [
        f"{kind}:{value}" for kind, values in registered_sources().items() if kind != "agent_type_discovered" for value in sorted(values)
    ]
    return [ref for ref in required if ref not in listed]


def implementing_module(ref: str) -> str | None:
    """Dotted module whose import a test must exercise for ``ref``."""
    kind, _, value = ref.partition(":")
    if kind == "symbol":
        return value.rpartition(":")[0]
    if kind == "cloud_provider":
        from agent_bom.cloud import _BUILTIN_PROVIDERS

        return _BUILTIN_PROVIDERS[value]
    if kind == "connector":
        from agent_bom.connectors import _BUILTIN_CONNECTORS

        return _BUILTIN_CONNECTORS[value]
    return {
        "agent_type": "agent_bom.discovery",
        "trace_connector": "agent_bom.trace_connectors",
        "export_kind": "agent_bom.export.destinations",
        "vector_db": "agent_bom.cloud.vector_db",
        "endpoint_provider": "agent_bom.connectors.endpoints",
    }.get(kind)


def more_label(group: Group) -> str:
    names = [item.name for item in group.text_only]
    return f"+{len(names)} more: " + " · ".join(names) if names else ""


def markdown_block(manifest: Manifest) -> str:
    rows = ["| Area | Integrations |", "|---|---|"]
    for group in (*manifest.groups, manifest.evidence_out):
        rows.append(f"| {group.title[:1].upper()}{group.title[1:]} | {', '.join(item.name for item in group.integrations)} |")
    body = "\n".join(rows)
    return f"{BLOCK_BEGIN}\n{body}\n\n{manifest.trademark_note}\n{BLOCK_END}"


def replace_block(text: str, block: str) -> str:
    start = text.index(BLOCK_BEGIN)
    end = text.index(BLOCK_END, start) + len(BLOCK_END)
    return text[:start] + block + text[end:]


def integration_directory(manifest: Manifest) -> str:
    """A static, searchable category directory for GitHub's noninteractive README."""
    groups = (*manifest.groups, manifest.evidence_out)
    lines = [
        "# Integration directory",
        "",
        "<!-- Generated by scripts/render_social_preview_svg.py; do not edit. -->",
        "",
        "Choose a category or search this page for a vendor. The banner shows selected marks; this directory lists "
        "every entry in the integration manifest.",
        "",
        " · ".join(f"[{group.title.capitalize()}](#{group.id})" for group in groups),
        "",
        "An integration is not a guarantee of every workflow. Discovery, saved connections, content sampling and "
        "runtime enforcement have different credential and collection boundaries.",
        "",
        "Read the [provider workflow boundaries](cloud/PROVIDER_WORKFLOW_BOUNDARIES.md) and [surface coverage "
        "matrix](VENDOR_COVERAGE.md) before choosing a deployment.",
        "",
        "Start with `uvx agent-bom scan .` for repository evidence, or use Connections in your own control plane to "
        "verify a supported read-only identity and run a scan. Inspect the findings and collection coverage before "
        "investigating paths. [Quick start](../README.md#quick-start).",
        "",
    ]
    for group in groups:
        lines += [f'<a id="{group.id}"></a>', "", f"## {group.title.capitalize()}", ""]
        if group is manifest.evidence_out:
            lines += ["Evidence destinations are output integrations; they are not source collectors.", ""]
        lines += ["| Integration | Implementation reference |", "| --- | --- |"]
        for item in group.integrations:
            refs = ", ".join(f"`{ref}`" for ref in item.implements)
            lines.append(f"| {item.name} | {refs} |")
        lines.append("")
    return "\n".join([*lines, manifest.trademark_note, ""])


def stale_doc_surfaces(manifest: Manifest) -> list[str]:
    block = markdown_block(manifest)
    stale = []
    for path in DOC_SURFACES:
        text = path.read_text(encoding="utf-8")
        if BLOCK_BEGIN not in text or replace_block(text, block) != text:
            stale.append(str(path.relative_to(ROOT)))
    directory = ROOT / "docs" / "INTEGRATIONS.md"
    if not directory.exists() or directory.read_text(encoding="utf-8") != integration_directory(manifest):
        stale.append("docs/INTEGRATIONS.md")
    return stale


def write_doc_surfaces(manifest: Manifest) -> None:
    (ROOT / "docs" / "INTEGRATIONS.md").write_text(integration_directory(manifest), encoding="utf-8")
    block = markdown_block(manifest)
    for path in DOC_SURFACES:
        text = path.read_text(encoding="utf-8")
        path.write_text(replace_block(text, block), encoding="utf-8")


if __name__ == "__main__":
    loaded = load()
    problems = [f"unresolved: {ref}" for ref in unresolved_refs(loaded)]
    problems += [f"not in manifest: {ref}" for ref in uncovered_sources(loaded)]
    print("\n".join(problems) or "integrations manifest OK")
    sys.exit(1 if problems else 0)
