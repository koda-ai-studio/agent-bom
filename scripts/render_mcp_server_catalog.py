"""Render the public MCP server risk catalog from the bundled registry.

The catalog page lists every registry entry that carries a reviewed risk level
(high, medium or low) with its justification, tools, credential variables and
source. Entries synced from public registries without a risk review are counted,
not listed: they are searchable with ``agent-bom registry search``.

Usage: python scripts/render_mcp_server_catalog.py [--check]
"""

from __future__ import annotations

import argparse
import html
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / "src" / "agent_bom" / "mcp_registry.json"
OUTPUT = ROOT / "site-docs" / "mcp-servers" / "index.md"
RISK_ORDER = ("high", "medium", "low")
RISK_TITLE = {"high": "High risk", "medium": "Medium risk", "low": "Low risk"}


def _text(value: object) -> str:
    """Plain registry text, safe inside Markdown prose."""
    return html.escape(" ".join(str(value).split()), quote=False)


def _code_list(values: list[Any]) -> str:
    return ", ".join(f"`{str(value).replace('`', '')}`" for value in values) or "none recorded"


def _entry(key: str, server: dict[str, Any]) -> list[str]:
    name = _text(server.get("name") or key)
    package = str(server.get("package") or key).replace("`", "")
    version = server.get("latest_version")
    lines = [f"### {name}", ""]
    lines.append(f"`{package}` ({_text(server.get('ecosystem') or 'unknown')}{f', {_text(version)}' if version else ''})")
    lines.append("")
    lines.append(f"- **Why {server['risk_level']}:** {_text(server['risk_justification'])}")
    lines.append(f"- **Category:** {_text(server.get('category') or 'uncategorized')}")
    lines.append(f"- **Tools ({len(server.get('tools') or [])}):** {_code_list(server.get('tools') or [])}")
    lines.append(f"- **Credential variables:** {_code_list(server.get('credential_env_vars') or [])}")
    review = "manually verified" if server.get("verified") else "curated, not yet manually verified"
    license_name = f" · license {_text(server['license'])}" if server.get("license") else ""
    lines.append(f"- **Review:** {review}{license_name}")
    if server.get("source_url"):
        lines.append(f"- **Source:** <{server['source_url']}>")
    lines.append("")
    return lines


def render(registry: dict[str, Any]) -> str:
    servers: dict[str, dict[str, Any]] = registry["servers"]
    assessed = {
        key: server
        for key, server in servers.items()
        if server.get("risk_level") in RISK_ORDER and str(server.get("risk_justification") or "").strip()
    }
    counts = {risk: sum(1 for server in assessed.values() if server["risk_level"] == risk) for risk in RISK_ORDER}
    unreviewed = len(servers) - len(assessed)
    out = [
        "<!-- Generated by scripts/render_mcp_server_catalog.py from src/agent_bom/mcp_registry.json; do not edit. -->",
        "",
        "# MCP server risk catalog",
        "",
        f"Risk notes for **{len(assessed)} MCP servers** whose capabilities agent-bom has reviewed: "
        f"{counts['high']} high, {counts['medium']} medium and {counts['low']} low. Each entry says why it has "
        "that risk level, which tools it exposes and which credential variables it reads.",
        "",
        "Check the servers configured on your own machine:",
        "",
        "```bash",
        "# Discover the agents and MCP servers on this machine, then scan them",
        "uvx agent-bom scan",
        "# Look up one server",
        "uvx agent-bom registry search <server>",
        "```",
        "",
        "## How to read this catalog",
        "",
        (
            "- **Risk level** describes what a server's tools can do (write files, run commands, reach cloud or data "
            "services), not a vulnerability. Package CVEs are reported by a scan."
        ),
        "- **Credential variables** are inferred from the server's documentation and configuration; confirm them against your own setup.",
        "- **Manually verified** entries were checked against the server's source by a maintainer.",
        f"- The registry also holds **{unreviewed} servers** synced from public MCP registries without a risk "
        "review yet. They are searchable with `agent-bom registry search`.",
        "",
        f"Registry updated {registry.get('_updated', 'unknown')}. "
        "[Suggest a correction](https://github.com/koda-ai-studio/agent-bom/issues/new?template=inaccurate_finding.yml).",
        "",
    ]
    for risk in RISK_ORDER:
        group = sorted(
            ((key, server) for key, server in assessed.items() if server["risk_level"] == risk),
            key=lambda item: str(item[1].get("name") or item[0]).lower(),
        )
        out += [f"## {RISK_TITLE[risk]} ({len(group)})", ""]
        for key, server in group:
            out += _entry(key, server)
    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the committed catalog is stale")
    args = parser.parse_args(argv)
    text = render(json.loads(REGISTRY.read_text(encoding="utf-8")))
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; run python scripts/render_mcp_server_catalog.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
