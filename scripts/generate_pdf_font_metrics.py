"""Extract ASCII WinAnsi Helvetica advances from Adobe's Core 14 AFM files.

Usage: python scripts/generate_pdf_font_metrics.py Helvetica.afm Helvetica-Bold.afm
AFM inputs: https://github.com/foliojs/pdfkit/tree/master/lib/font/data
These are measurements only; no font program is embedded.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path


def widths(path: Path) -> list[int]:
    rows = re.findall(r"^C (-?\d+) ; WX (\d+) ; N (\S+) ;", path.read_text(), re.MULTILINE)
    by_code = {int(code): int(width) for code, width, _name in rows}
    by_name = {name: int(width) for _code, width, name in rows}
    # WinAnsi uses straight quotes and grave where Adobe StandardEncoding differs.
    by_code.update({39: by_name["quotesingle"], 96: by_name["grave"]})
    return [by_code[code] for code in range(32, 127)]


def main() -> None:
    target = Path(__file__).resolve().parents[1] / "src/agent_bom/output/pdf_font_metrics.py"
    lines = [
        '"""Generated by scripts/generate_pdf_font_metrics.py from Adobe Core 14 AFMs.',
        "Metrics copyright (c) 1985, 1987, 1989, 1990, 1997 Adobe Systems Incorporated.",
        "All Rights Reserved. Widths are in thousandths of an em.",
        '"""',
        "",
    ]
    for label, path in zip(("REGULAR", "BOLD"), sys.argv[1:], strict=True):
        values = widths(Path(path))
        lines.append(f"{label} = (")
        lines.extend("    " + ", ".join(map(str, values[i : i + 16])) + "," for i in range(0, len(values), 16))
        lines.extend(
            [
                ")",
                "",
            ]
        )
    target.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
